export interface AgentManifest {
  id: string
  name: string
  version: string
  /** 人设与话术原则。v1.0 约定：主 Agent 是测试探针，≤20 行 */
  persona: string
  /** 能力白名单，支持通配。平台据此裁剪 schema 与拦截调用 */
  tools: string[]
  context: Array<'vehicleState' | 'capabilities' | 'speaker' | 'environment' | 'desktop'>
  maxRounds: number
  /** 常驻工具（全 schema 永远在）：语音/卡片/记忆这类高频管道。仅慢层用 */
  resident?: string[]
  /** 过滤器架构下的协作职责段，pipeline 拼在 persona 之后。仅慢层用 */
  role?: string
  /** 技能包（二级披露：目录行常驻 + skill.use 注入正文）。仅慢层与子 Agent 用 */
  skills?: Array<{ name: string; whenToUse: string; inject: string; tools?: string[] }>
}

